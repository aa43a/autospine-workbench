import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const [output,deps,chrome,run]=process.argv.slice(2);
const {chromium}=await import(pathToFileURL(path.resolve(deps,'node_modules/playwright-core/index.mjs')));
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({executablePath:chrome,headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],writes=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('request',r=>{if(r.method()==='POST')writes.push(new URL(r.url()).pathname);});
 await page.goto(`http://127.0.0.1:8918/production.html?run=${run}`);
 const panel=page.locator('#revision-panel');
 await page.waitForFunction(()=>{const select=document.querySelector('[aria-label="身体修复版本"]');return select&&!select.disabled;});
 await panel.getByRole('button',{name:'预览受影响步骤'}).click();
 await panel.getByRole('button',{name:'按此范围创建修正任务'}).waitFor();
 const initial=await panel.innerText();assert.match(initial,/沿用：.*身体动作/);
 await panel.getByRole('spinbutton').fill('30');
 assert.equal(await panel.getByRole('button',{name:'按此范围创建修正任务'}).count(),0);
 await panel.getByRole('button',{name:'预览受影响步骤'}).click();
 await panel.getByRole('button',{name:'按此范围创建修正任务'}).waitFor();
 const changed=await panel.innerText();assert.match(changed,/重建：.*身体动作.*联合动画/);
 await panel.screenshot({path:path.join(output,'rebuild-plan.png')});
 const evidence=page.locator('#evidence');
 await evidence.getByText('追溯身体动作原候选的异常',{exact:true}).click();
 const body=evidence.locator('details').filter({has:page.getByText('追溯身体动作原候选的异常',{exact:true})});
 await body.getByRole('button',{name:'检查可用范围与待处理项'}).click();
 const detail=body.locator('details').filter({has:page.locator('summary', {hasText:'异常定位（报告返回'})}).first();
 await detail.locator('summary').click();
 const point=detail.locator('a').first();await point.click();
 const frame=body.locator('iframe');await frame.waitFor({state:'visible'});
 const player=await (await frame.elementHandle()).contentFrame();
 await player.waitForFunction(()=>window.characterPlayerReady===true,{},{timeout:120000});
 const source=await (await page.request.get(`http://127.0.0.1:8918/api/production/${run}`)).json();
 assert.equal(await player.evaluate(()=>window.characterPlayerControl.artifact),source.stages.body.artifact_sha256);
 assert.ok(await frame.getAttribute('src'));
 await evidence.screenshot({path:path.join(output,'same-page-inspection.png')});
 await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);assert.ok(writes.every(url=>url.endsWith('/revision-plan')));
 await fs.writeFile(path.join(output,'report.json'),JSON.stringify({passed:true,run,initial,changed,errors,writes,builds_created:false,acceptance_written:false},null,2));
 console.log(JSON.stringify({passed:true,run}));
}finally{await browser.close();}
