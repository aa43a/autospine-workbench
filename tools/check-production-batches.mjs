import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const [output,deps,chrome,batch]=process.argv.slice(2);
await fs.mkdir(output,{recursive:true});
const {chromium}=await import(pathToFileURL(path.resolve(deps,'node_modules/playwright-core/index.mjs')));
const browser=await chromium.launch({executablePath:chrome,headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(`http://127.0.0.1:8918/production.html?batch=${batch}`);
  await page.getByRole('heading',{name:'批次进度 · 2 / 2 已生成候选'}).waitFor();
  await page.getByText('批量制作 · 选择多个角色和动作',{exact:true}).click();
  await page.locator('#batch-projects input').nth(0).check();
  await page.locator('#batch-projects input').nth(1).check();
  await page.locator('#batch-sources input').nth(0).check();
  assert.match(await page.locator('#batch-count').innerText(),/^2 /);
  await page.getByRole('button',{name:'检查多动作包兼容性',exact:true}).click();
  await page.getByText('这里只检查骨架与贴图兼容性。合并后的 Runtime 和视觉验收仍需单独验证。',{exact:true}).waitFor();
  assert.equal(await page.locator('#batch-detail table tr').count(),3);
  await page.getByRole('button',{name:'在本页查看',exact:true}).first().click();
  await page.waitForSelector('#player:not([hidden])');
  const player=page.frameLocator('#player');
  await player.locator('#play:not([disabled])').waitFor({timeout:60000});
  await player.locator('#time').focus();await player.locator('#time').press('End');
  assert.doesNotMatch(await player.locator('#position').innerText(),/^0\.000 /);
  await player.locator('#reset').click();
  await player.locator('#play').click();
  assert.equal(await player.locator('#play').innerText(),'暂停');
  await player.locator('#play').click();
  assert.match(page.url(),/production.html\?run=/);
  await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  assert.equal(overflow,false);
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(output,'report.json'),JSON.stringify({passed:true,batch,errors,overflow,stage_review_saved:false},null,2));
  console.log(JSON.stringify({passed:true,batch}));
}finally{await browser.close();}
