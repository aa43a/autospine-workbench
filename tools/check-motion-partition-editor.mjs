import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const [base,job,output,dependencies]=process.argv.slice(2);
const {chromium}=await import(pathToFileURL(path.resolve(dependencies,'node_modules/playwright-core/index.mjs')));
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/motions.html#'+job);const card=page.locator('#'+job);
 await card.getByRole('button',{name:'检查可用范围与待处理项',exact:true}).click();
 await card.getByRole('button',{name:'查看变形区域与处理方案',exact:true}).click({timeout:120000});
 const editor=card.getByRole('group',{name:'当前异常的处理草稿',exact:true}).first();
 await editor.getByRole('button',{name:'加载处理草稿',exact:true}).click();
 await editor.getByRole('button',{name:'保存处理草稿',exact:true}).waitFor();
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='保存处理草稿'&&!b.disabled));
 await editor.getByLabel('异常处理路线',{exact:true}).selectOption('partition');
 const pending=page.waitForResponse(r=>r.url().endsWith('/partition-mesh.json'));
 await editor.getByRole('button',{name:'在原纹理上划分区域',exact:true}).click();
 const report=await (await pending).json();const mesh=report.rows.find(r=>r.slot==='layer-004');assert.ok(mesh);
 const canvas=editor.getByLabel('区域三角形选择画布',{exact:true});await editor.getByText(/已选择 0 个三角形/).waitFor();
 const tri=mesh.triangles.slice(0,3);const uv=[0,1].map(k=>tri.reduce((s,v)=>s+mesh.uvs[2*v+k]/3,0));
 await canvas.scrollIntoViewIfNeeded();const box=await canvas.boundingBox();
 await page.mouse.click(box.x+uv[0]*box.width,box.y+uv[1]*box.height);
 await editor.getByLabel('区域目标骨骼',{exact:true}).selectOption('hand_l');
 await editor.getByLabel('异常处理说明',{exact:true}).fill('UI regression draft; partition editor verification; withdraw after check');
 const saved=page.waitForResponse(r=>r.url().endsWith('/repair-draft')&&r.request().method()==='POST');
 await editor.getByRole('button',{name:'保存处理草稿',exact:true}).click();
 const state=await (await saved).json(),region=state.history.at(-1).partition;assert.ok(region.triangles.length);assert.equal(region.bone,'hand_l');
 const restored=page.waitForResponse(r=>r.url().endsWith('/repair-draft')&&r.request().method()==='GET');
 await editor.getByRole('button',{name:'加载处理草稿',exact:true}).click();
 assert.deepEqual((await (await restored).json()).history.at(-1).partition,region);
 await page.waitForFunction(()=>[...document.querySelectorAll('fieldset')].some(f=>f.querySelector('legend')?.textContent==='当前异常的处理草稿'&&!f.disabled));
 await editor.getByText(new RegExp('已选择 '+region.triangles.length+' 个三角形')).waitFor();
 await fs.mkdir(output,{recursive:true});await editor.screenshot({path:path.join(output,'partition.png')});
 await editor.getByLabel('异常处理路线',{exact:true}).selectOption('withdraw');
 const withdrawn=page.waitForResponse(r=>r.url().endsWith('/repair-draft')&&r.request().method()==='POST');
 await editor.getByRole('button',{name:'保存处理草稿',exact:true}).click();
 assert.equal((await (await withdrawn).json()).history.at(-1).action,'withdraw');assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(output,'check.json'),JSON.stringify({passed:true,region,errors,withdrawn:true}));console.log(JSON.stringify({passed:true,count:region.triangles.length}));
} finally {await browser.close();}
