import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const source=await fs.readFile(new URL('../web/modules/view-pose-state.js',import.meta.url),'utf8');
const {createViewState}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const template={request:{draft_revision:1},view_pose:{interval:[0,4],poses:[]},control_template:{mesh_sha256:'source',source_uv:[[0,0],[1,0],[0,1]],target_uv:[[0,0],[1,0],[0,1]],target_xy:[[0,0],[10,0],[0,10]],triangles:[[0,1,2]]}};
const before=structuredClone(template),state=createViewState(template);
assert.throws(()=>state.export(),/保存/);
state.move('pose',1,[12,0]);state.save(1,0,4);
state.move('pose',1,[16,0]);state.save(3,0,4);
state.sample(2);assert.deepEqual(state.points[1],[14,0]);
assert.deepEqual(state.export().view_pose.poses.map(p=>p.correspondence.target_xy[1]),[[12,0],[16,0]]);
state.move('uv',1,[.9,.1]);
assert.ok(state.export().view_pose.poses.every(p=>p.correspondence.target_uv[1][0]===.9));
assert.deepEqual(state.controls.source_uv,template.control_template.source_uv);
assert.throws(()=>state.move('uv',1,[2,0]),/图片内/);
assert.throws(()=>state.save(0,0,4),/严格/);
assert.throws(()=>state.save(2,1.5,4),/超出/);
assert.equal(state.export().view_pose.poses.length,2);
state.save(3,0,4);assert.equal(state.export().view_pose.poses.length,2);
state.remove(1);assert.deepEqual(state.export().view_pose.poses.map(p=>p.time),[3]);
assert.deepEqual(template,before);
console.log('View pose state: isolation, interpolation, shared UV, interval and deletion checks passed');
